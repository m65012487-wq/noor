// Силуэт скачущей лошади, параметрический.
//
// Всё рисуется одним цветом, поэтому можно свободно мешать заливки и толстые
// обводки: они сливаются в одну фигуру. Ноги собираются из отрезков с круглыми
// концами — сустав получается сам собой, без вычисления контура.
//
// Пропорции взяты от настоящей лошади, а не на глаз. Длина корпуса L принята
// за единицу, от неё считается всё; высота в холке выходит около 0.89L. Две
// ошибки, стоившие двух переделок: слишком глубокий и короткий корпус (лошадь
// читалась бочкой на ножках) и слишком поднятая шея — у скачущей лошади она
// вытянута вперёд почти горизонтально, а не поставлена как у стоящей.
//
// dir: 1 — мордой вправо, −1 — влево.

const rad = (d) => (d * Math.PI) / 180;

// Лента переменной ширины по осевой линии — для гривы и хвоста. Закрытым
// контуром из двух дуг они получались полумесяцами, висящими отдельно от
// тела: обратная дуга уходила от прямой и у основания оставался зазор.
function ribbon(pts, widths, fill) {
  const n = pts.length;
  const left = [];
  const right = [];
  for (let i = 0; i < n; i += 1) {
    const [x, y] = pts[i];
    const [ax, ay] = pts[Math.max(0, i - 1)];
    const [bx, by] = pts[Math.min(n - 1, i + 1)];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    const nx = -dy / len;
    const ny = dx / len;
    const w = widths[i] / 2;
    left.push([x + nx * w, y + ny * w]);
    right.push([x - nx * w, y - ny * w]);
  }
  const pt = ([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`;
  let d = `M ${pt(left[0])}`;
  for (let i = 1; i < n; i += 1) d += ` L ${pt(left[i])}`;
  for (let i = n - 1; i >= 0; i -= 1) d += ` L ${pt(right[i])}`;
  return `<path d="${d} Z" fill="${fill}"/>`;
}

// Нога: предплечье, голень, копыто. Углы от вертикали вниз, плюс — вперёд.
function leg(x, y, L, dir, a1, a2, w1, w2, fill) {
  const l1 = L * 0.27;
  const l2 = L * 0.28;
  const l3 = L * 0.07;
  const kx = x + dir * Math.sin(rad(a1)) * l1;
  const ky = y + Math.cos(rad(a1)) * l1;
  const fx = kx + dir * Math.sin(rad(a2)) * l2;
  const fy = ky + Math.cos(rad(a2)) * l2;
  const hx = fx + dir * Math.sin(rad(a2 * 0.3)) * l3;
  const hy = fy + Math.cos(rad(a2 * 0.3)) * l3;
  const seg = (ax, ay, bx, by, w) => `<path d="M ${ax.toFixed(1)} ${ay.toFixed(1)} `
    + `L ${bx.toFixed(1)} ${by.toFixed(1)}" stroke="${fill}" stroke-width="${w.toFixed(2)}" `
    + `stroke-linecap="round" fill="none"/>`;
  return seg(x, y, kx, ky, w1) + seg(kx, ky, fx, fy, w2) + seg(fx, fy, hx, hy, w2 * 1.3);
}

// Четыре положения галопного цикла: вынос передних, полное растяжение,
// подвисание со сбором под корпус, толчок задних. Табун в одной фазе читается
// шеренгой одинаковых фигур, а не движением.
const GAITS = [
  { f1: [50, 66], f2: [26, 46], h1: [-30, 6], h2: [-8, 26] },
  { f1: [-6, 22], f2: [-24, 4], h1: [-56, -74], h2: [-40, -60] },
  { f1: [24, 62], f2: [6, 44], h1: [30, 4], h2: [46, 18] },
  { f1: [56, 78], f2: [38, 62], h1: [-50, -26], h2: [-30, -6] },
];

function horse(x, y, L, dir, phase, fill, opts = {}) {
  const { mane = true, tail = true } = opts;
  const g = GAITS[((phase % GAITS.length) + GAITS.length) % GAITS.length];
  const px = (u) => +(x + dir * L * u).toFixed(1);
  const py = (v) => +(y + L * v).toFixed(1);
  const p = (u, v) => `${px(u)} ${py(v)}`;
  const uv = (u, v) => [px(u), py(v)];

  const shX = px(0.28);
  const shY = py(0.10);
  const hpX = px(-0.26);
  const hpY = py(0.06);
  const w1 = L * 0.052;
  const w2 = L * 0.030;

  // Дальняя пара ног уходит под корпус — рисуется первой.
  let out = leg(shX - dir * L * 0.035, shY, L, dir, g.f2[0], g.f2[1], w1 * 0.85, w2 * 0.85, fill)
    + leg(hpX - dir * L * 0.035, hpY, L, dir, g.h2[0], g.h2[1], w1 * 0.85, w2 * 0.85, fill);

  // Корпус: холка, прогиб спины, круп, подтянутый пах, глубокая грудь.
  out += `<path d="M ${p(0.42, 0.02)} `
    + `C ${p(0.40, -0.10)} ${p(0.34, -0.16)} ${p(0.26, -0.17)} `
    + `C ${p(0.12, -0.18)} ${p(0.00, -0.14)} ${p(-0.14, -0.16)} `
    + `C ${p(-0.26, -0.18)} ${p(-0.38, -0.14)} ${p(-0.42, -0.02)} `
    + `C ${p(-0.45, 0.05)} ${p(-0.38, 0.11)} ${p(-0.26, 0.11)} `
    + `C ${p(-0.10, 0.11)} ${p(0.06, 0.14)} ${p(0.18, 0.17)} `
    + `C ${p(0.30, 0.19)} ${p(0.40, 0.13)} ${p(0.42, 0.02)} Z" fill="${fill}"/>`;

  // Шея и голова одним контуром: по гребню вперёд к затылку, через лоб вниз
  // по морде, назад под ганашом и по горлу к груди.
  out += `<path d="M ${p(0.24, -0.17)} `
    + `C ${p(0.40, -0.28)} ${p(0.58, -0.38)} ${p(0.70, -0.46)} `
    + `C ${p(0.76, -0.50)} ${p(0.82, -0.46)} ${p(0.85, -0.40)} `
    + `C ${p(0.90, -0.36)} ${p(0.93, -0.32)} ${p(0.93, -0.28)} `
    + `C ${p(0.93, -0.245)} ${p(0.89, -0.235)} ${p(0.85, -0.25)} `
    + `C ${p(0.78, -0.27)} ${p(0.71, -0.30)} ${p(0.66, -0.31)} `
    + `C ${p(0.58, -0.24)} ${p(0.50, -0.14)} ${p(0.43, -0.02)} Z" fill="${fill}"/>`;
  // Ухо у затылка, отклонённое назад ходом.
  out += `<path d="M ${p(0.735, -0.475)} L ${p(0.685, -0.565)} L ${p(0.775, -0.49)} Z" fill="${fill}"/>`;

  // Грива и хвост кладутся ОСЬЮ на тело, а не встык к контуру: при стыковке
  // по краю между лентой и силуэтом оставалась щель в фон толщиной в волос.
  if (mane) {
    out += ribbon([
      uv(0.72, -0.465), uv(0.63, -0.435), uv(0.52, -0.37),
      uv(0.40, -0.30), uv(0.29, -0.225), uv(0.22, -0.17),
    ], [L * 0.03, L * 0.055, L * 0.065, L * 0.065, L * 0.055, L * 0.04], fill);
  }

  // Хвост стелется назад почти горизонтально: на скорости его несёт потоком,
  // а не роняет вниз.
  if (tail) {
    out += ribbon([
      uv(-0.36, -0.15), uv(-0.52, -0.135), uv(-0.66, -0.065),
      uv(-0.78, 0.045), uv(-0.87, 0.175),
    ], [L * 0.065, L * 0.105, L * 0.115, L * 0.08, L * 0.025], fill);
  }

  // Ближняя пара ног — поверх корпуса.
  out += leg(shX, shY, L, dir, g.f1[0], g.f1[1], w1, w2, fill)
    + leg(hpX, hpY, L, dir, g.h1[0], g.h1[1], w1, w2, fill);

  return out;
}

module.exports = { horse, GAITS };
